"""Generate supabase/functions/_shared/wired-pdf-content.ts from Camila's APPROVED copy (docs/wired-copy/).

Run from the repo root:  python scripts/gen_wired_pdf_content.py
Every string is copied word for word. Only text under '### ' headings is taken (the '## ' notes are
Lane notes, not customer copy). The pair blurbs and the 9 write-ups have their own shapes.
src/test/wiredPdfContent.test.ts re-reads the approved files and fails if anything here drifts.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs" / "wired-copy"
OUT = ROOT / "supabase" / "functions" / "_shared" / "wired-pdf-content.ts"

SECTIONED = {
    "blueprint1": "Wired_Quiz_Blueprint_Part1.md",
    "blueprint2": "Wired_Quiz_Blueprint_Part2.md",
    "familyMap": "Wired_Quiz_Family_Map_And_Screens.md",
    "results": "Wired_Quiz_Results_Page_Copy.md",
    "emails": "Wired_Quiz_Emails_Transactional.md",
}


def read(name: str) -> list[str]:
    return (DOCS / name).read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")


def sections(lines: list[str], level: int = 3) -> dict:
    """{ heading: [ {t:'p'|'li', s:str}, ... ] } in file order, for headings at `level` ('###' by
    default; the emails file uses '##'). A higher-level heading resets."""
    out: dict = {}
    cur = None
    mark = "#" * level + " "
    for raw in lines:
        line = raw.rstrip()
        if line.startswith(mark):
            cur = line[len(mark):].strip()
            out[cur] = []
            continue
        if line.startswith("#") or line.strip() == "---":
            cur = None
            continue
        if cur is None or not line.strip():
            continue
        if line.startswith("- "):
            out[cur].append({"t": "li", "s": line[2:].strip()})
        else:
            out[cur].append({"t": "p", "s": line.strip()})
    return out


def pair_blurbs() -> dict:
    out = {}
    for line in read("Wired_Quiz_Pair_Blurbs.md"):
        m = re.match(r"^- \*\*(.+?)\*\* \(`([a-z]+\+[a-z]+)`\): (.+)$", line.strip())
        if m:
            out[m.group(2)] = m.group(3).strip()
    return out


def writeups() -> dict:
    out = {}
    lines = read("Wired_Quiz_Wiring_Writeups.md")
    name = None
    mode = None
    for raw in lines:
        line = raw.rstrip()
        if line.startswith("## "):
            name = line[3:].strip()
            out[name.lower()] = {"name": name, "bible": "", "short": [], "longer": []}
            mode = None
            continue
        if name is None or not line.strip() or line.strip() == "---":
            continue
        w = out[name.lower()]
        if line.startswith("**Bible example:**"):
            w["bible"] = line[len("**Bible example:**"):].strip()
        elif line.strip() == "**Short version**":
            mode = "short"
        elif line.strip() == "**Longer version**":
            mode = "longer"
        elif mode == "short":
            w["short"].append(line.strip())
        elif mode == "longer":
            # *Lead.* rest  ->  {lead, text}
            m = re.match(r"^\*(.+?)\*\s*(.*)$", line.strip())
            if m:
                w["longer"].append({"lead": m.group(1).strip(), "text": m.group(2).strip()})
            else:
                w["longer"].append({"lead": "", "text": line.strip()})
    return out


def main() -> None:
    data = {k: sections(read(v), 2 if k == "emails" else 3) for k, v in SECTIONED.items()}
    data["pairs"] = pair_blurbs()
    data["writeups"] = writeups()
    assert len(data["pairs"]) == 36, len(data["pairs"])
    assert len(data["writeups"]) == 9, list(data["writeups"])
    body = json.dumps(data, ensure_ascii=False, indent=1)
    OUT.write_text(
        "// GENERATED by scripts/gen_wired_pdf_content.py from docs/wired-copy/ (Camila's APPROVED copy,\n"
        "// word for word). Do not hand-edit: src/test/wiredPdfContent.test.ts checks it against the files.\n\n"
        "export type CopyItem = { t: 'p' | 'li'; s: string };\n"
        "export type Writeup = { name: string; bible: string; short: string[]; longer: { lead: string; text: string }[] };\n"
        "export interface WiredPdfCopy {\n"
        "  blueprint1: Record<string, CopyItem[]>;\n  blueprint2: Record<string, CopyItem[]>;\n"
        "  familyMap: Record<string, CopyItem[]>;\n  results: Record<string, CopyItem[]>;\n  emails: Record<string, CopyItem[]>;\n"
        "  pairs: Record<string, string>;\n  writeups: Record<string, Writeup>;\n}\n\n"
        f"export const WIRED_PDF_COPY: WiredPdfCopy = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{k}={len(v)}" for k, v in data.items()))


if __name__ == "__main__":
    main()
